/**
 * Renders the frontend's static template pictures, so the pages that show
 * them never wait on this backend:
 *
 *  - resume/public/landing-templates/<id>.webp: the landing page's template wall
 *  - resume/assets/og/templates/<id>.png: share images (Spark behind the page
 *    cards, each template on its own page's card)
 *  - resume/src/lib/og/template-names.generated.ts: those templates' names
 *
 * Each is the template's first page with its sample CV, exactly as the
 * gallery thumbnails render. Run from resume-back after changing a template's
 * look, or adding one (the frontend repo is expected next to this one):
 *
 *   npx tsx scripts/render-frontend-template-pictures.ts
 */
import http from "node:http";
import fs from "node:fs/promises";
import path from "node:path";
import puppeteer from "puppeteer";
import { renderCvHtml, FONTS_DIR } from "../src/services/render.service";
import { sampleCvFor } from "../src/config/sample-cv";
import { CV_TEMPLATE_REGISTRY } from "../src/config/cv-templates";

const FRONTEND = path.resolve(__dirname, "../../resume");

/** The landing wall's templates (see WALL_TEMPLATES in the frontend's TemplatesSection). */
const WALL = ["midnight", "classic", "spark", "linen", "minimal", "clarity", "formal", "banner", "focus", "stack", "prose", "research"];

/** Every public template (the photo ones are hidden from the app for now). */
const PUBLIC = Object.values(CV_TEMPLATE_REGISTRY).filter((t) => !t.sections.includes("photo"));

async function main() {
  // Serve the template fonts over loopback, as the backend does.
  const server = http.createServer(async (req, res) => {
    try {
      const file = path.join(FONTS_DIR, decodeURIComponent((req.url ?? "").replace(/^\/fonts\//, "")));
      if (!file.startsWith(FONTS_DIR)) throw new Error("bad path");
      res.writeHead(200, { "Content-Type": "font/woff2" });
      res.end(await fs.readFile(file));
    } catch {
      res.writeHead(404).end();
    }
  });
  await new Promise<void>((resolve) => server.listen(0, "127.0.0.1", resolve));
  const fontBaseUrl = `http://127.0.0.1:${(server.address() as { port: number }).port}/fonts`;

  const wallDir = path.join(FRONTEND, "public/landing-templates");
  const ogDir = path.join(FRONTEND, "assets/og/templates");
  await fs.mkdir(wallDir, { recursive: true });
  await fs.mkdir(ogDir, { recursive: true });

  const browser = await puppeteer.launch({ headless: true });
  const shoot = async (id: string, file: string, type: "png" | "webp") => {
    const html = await renderCvHtml(sampleCvFor(id), id, { mode: "thumbnail", fontBaseUrl });
    const page = await browser.newPage();
    try {
      await page.setJavaScriptEnabled(false);
      // A4 at 794 CSS px wide, captured at 0.6× (476×674): sharp at the sizes they're shown.
      await page.setViewport({ width: 794, height: 1123, deviceScaleFactor: 0.6 });
      await page.setContent(html, { waitUntil: "load" });
      await page.evaluateHandle("document.fonts.ready");
      await page.screenshot({ path: file as `${string}.png`, type, ...(type === "webp" ? { quality: 82 } : {}), clip: { x: 0, y: 0, width: 794, height: 1123 } });
    } finally {
      await page.close();
    }
  };

  try {
    for (const id of WALL) {
      await shoot(id, path.join(wallDir, `${id}.webp`), "webp");
      console.log("wall", id);
    }
    for (const t of PUBLIC) {
      await shoot(t.id, path.join(ogDir, `${t.id}.png`), "png");
      console.log("share image", t.id);
    }
  } finally {
    await browser.close();
    server.close();
  }

  const names = Object.fromEntries(PUBLIC.map((t) => [t.id, t.name]));
  await fs.writeFile(
    path.join(FRONTEND, "src/lib/og/template-names.generated.ts"),
    `// Generated by resume-back/scripts/render-frontend-template-pictures.ts — don't edit by hand.\n` +
      `// The public templates with a picture in assets/og/templates/, and their names.\n` +
      `export const TEMPLATE_NAMES: Record<string, string> = ${JSON.stringify(names, null, 2)};\n`
  );
  console.log(`done: ${WALL.length} wall pictures, ${PUBLIC.length} share pictures`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
