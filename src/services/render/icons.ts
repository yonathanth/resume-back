/** Icon for a contact link, from its label or URL (GitHub, LinkedIn, else a generic link). */
export function iconForLink(label: string, url: string): string {
  const text = `${label} ${url}`.toLowerCase();
  if (text.includes("github")) return "github";
  if (text.includes("linkedin")) return "linkedin";
  return "link";
}
